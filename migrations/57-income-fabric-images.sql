-- ============================================================================
-- صور الأقمشة على مبيعات الأقمشة (Fabric Sale Images)
-- ============================================================================
-- الهدف:
--   السماح بإرفاق صور القماش المباع داخل سجل المبيعة (income)، خصوصاً لقماش
--   "الشك". تُخزَّن الصور كروابط عامة (Storage URLs) في مصفوفة نصية، بحيث يمكن
--   لاحقاً عرض جميع صور أقمشة الشك المرفوعة عبر الفواتير في صفحة معرض مخصصة.
--
--   يمكن أيضاً إضافة/تعديل/حذف الصور على المبيعات القديمة عبر زر التعديل.
-- ============================================================================

ALTER TABLE income
ADD COLUMN IF NOT EXISTS fabric_images TEXT[] DEFAULT '{}';

COMMENT ON COLUMN income.fabric_images IS 'روابط صور القماش المباع (تُستخدم خصوصاً لقماش الشك)';

-- فهرس جزئي لتسريع جلب المبيعات التي تحتوي على صور
CREATE INDEX IF NOT EXISTS idx_income_fabric_images
  ON income USING GIN (fabric_images)
  WHERE fabric_images IS NOT NULL;

