-- ============================================================================
-- سعر بيع الوحدة لمخزون الأقمشة
-- ============================================================================
-- الهدف:
--   إضافة عمود «سعر البيع للوحدة» إلى أصناف مخزون الأقمشة. لازم لإنشاء منتجات
--   الأستاذ «مع تتبّع المخزون» (supports_inventory) التي تشترط سعر الشراء
--   (cost_per_unit الموجود مسبقاً) وسعر البيع معاً.
--
--   ⚠️ هذه الهجرة مطلوبة مع النشر (deploy).
-- ============================================================================

ALTER TABLE fabric_inventory
  ADD COLUMN IF NOT EXISTS sale_price_per_unit DECIMAL(12, 2);

COMMENT ON COLUMN fabric_inventory.sale_price_per_unit
  IS 'سعر بيع الوحدة (ر.س) — يُرسَل كـ sale_price لمنتج القماش في الأستاذ';

