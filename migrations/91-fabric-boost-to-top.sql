-- ============================================================================
-- Migration 91: زر «رفع» للقماش في إدارة متجر الأقمشة (Fabric Boost To Top)
-- ----------------------------------------------------------------------------
-- الهدف:
--   زر «رفع» على بطاقة القماش في /dashboard/fabrics يجعل القماش النتيجة الأولى
--   في المتجر (الترتيب الافتراضي «الأحدث أولاً»).
--
--   • عمود مستقل `boosted_at` بدل تعديل `created_at` حتى يبقى تاريخ الإضافة
--     الحقيقي محفوظاً.
--   • المتجر يرتّب «الأحدث أولاً» حسب الأحدث من (boosted_at, created_at)؛
--     فالقماش المرفوع يتصدّر، ويتقدّم عليه لاحقاً قماش جديد أو قماش رُفع بعده.
--   • الزائر (anon) يقرأ أعمدة fabrics بمنح عمود-بعمود (الدفعة D) ⇒ يُمنح العمود.
--
--   ⚠️ هذه الهجرة مطلوبة قبل النشر (deploy): الموقع يطلب العمود في كل قراءة
--   للأقمشة، فبدونها يفشل تحميل المتجر.
-- ============================================================================

ALTER TABLE public.fabrics
  ADD COLUMN IF NOT EXISTS boosted_at TIMESTAMPTZ;

COMMENT ON COLUMN public.fabrics.boosted_at IS
  'آخر وقت ضُغط فيه زر «رفع» في إدارة المتجر. يُستعمل في ترتيب «الأحدث أولاً» بدل created_at إن كان أحدث. فارغ = لم يُرفع.';

GRANT SELECT (boosted_at) ON TABLE public.fabrics TO anon;

