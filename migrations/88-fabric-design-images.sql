-- ============================================================================
-- Migration 88: صور تصاميم الفساتين لكل قماش (Fabric Design Images)
-- ----------------------------------------------------------------------------
-- الهدف:
--   السماح بإرفاق صور "تصميم فستان" لكل قماش داخل صفحة إدارة متجر الأقمشة،
--   بحيث يعرف الموقع أنها صور تصاميم نهائية وليست صوراً عادية للقماش.
--
--   • تُخزَّن كروابط عامة (Storage URLs) في عمود مستقل عن `images`.
--   • عمود مستقل تماماً ⇒ لا تمسّه مزامنة المخزون
--     (private.sync_fabric_store_listing تُحدّث `images` فقط).
--   • في المتجر: زر «عرض التصاميم النهائية للأقمشة» يبدّل صورة البطاقة إلى
--     أول صورة تصميم للأقمشة التي تملك تصاميم، والباقي يبقى كما هو.
--
--   ⚠️ هذه الهجرة مطلوبة مع النشر (deploy).
-- ============================================================================

ALTER TABLE fabrics
  ADD COLUMN IF NOT EXISTS design_images TEXT[] DEFAULT '{}';

COMMENT ON COLUMN fabrics.design_images IS
  'روابط صور تصاميم الفساتين المنفَّذة من هذا القماش (منفصلة عن images لتمييزها في الواجهة). فارغة = لا يوجد تصاميم.';

-- فهرس جزئي لتسريع جلب الأقمشة التي تملك تصاميم
CREATE INDEX IF NOT EXISTS idx_fabrics_design_images
  ON fabrics USING GIN (design_images)
  WHERE design_images IS NOT NULL AND array_length(design_images, 1) > 0;

