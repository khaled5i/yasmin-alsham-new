-- ============================================================================
-- فصل طريقة الدفع بين العربون والمتبقي (كاش / شبكة)
-- ============================================================================
-- الهدف:
--   دعم دفعتين لكل طلب تفصيل — العربون المبدئي (عند الإنشاء) والدفعة المتبقية
--   (عند التسليم) — مع تسجيل طريقة كلٍّ منهما (كاش أو شبكة). يُستخدم هذا لاحقاً
--   لإرسال «مبلغ الشبكة فقط» تلقائياً إلى المحاسبة (الأستاذ).
--
--   • payment_method (موجود مسبقاً) = طريقة دفع العربون.
--   • remaining_payment_method (جديد) = طريقة دفع المتبقي عند التسليم.
--   • deposit_amount (جديد) = مقدار العربون (كل ما دُفع قبل التسليم) — لقطة تُثبَّت
--       عند التسليم كي لا يضيع عند تحديث paid_amount ليساوي السعر الكامل.
--
--   ⚠️ هذه الهجرة مطلوبة مع النشر (deploy).
-- ============================================================================

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS remaining_payment_method VARCHAR(20),
  ADD COLUMN IF NOT EXISTS deposit_amount DECIMAL(12, 2);

COMMENT ON COLUMN orders.remaining_payment_method
  IS 'طريقة دفع المبلغ المتبقي عند التسليم: cash (كاش) أو card (شبكة)';

COMMENT ON COLUMN orders.deposit_amount
  IS 'مقدار العربون (ما دُفع قبل التسليم) — لقطة لتفصيل الكاش/الشبكة وإرسال مبلغ الشبكة للمحاسبة';

