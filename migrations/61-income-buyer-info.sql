-- ============================================================================
-- اسم العميل ورقم الهاتف على مبيعات الأقمشة (Buyer Info on Fabric Sales)
-- ============================================================================
-- الهدف:
--   السماح بتسجيل اسم العميل ورقم هاتفه (اختيارياً) عند إضافة مبيعة قماش.
--   لا يمكن استخدام عمود customer_name الموجود لأنه يُخزِّن اسم القماش
--   المباع (من المخزون) وليس اسم العميل الفعلي.
--
--   الحقلان اختياريان تماماً — حفظ المبيعة لا يتطلب تعبئتهما.
-- ============================================================================

ALTER TABLE income
ADD COLUMN IF NOT EXISTS buyer_name TEXT,
ADD COLUMN IF NOT EXISTS buyer_phone TEXT;

COMMENT ON COLUMN income.buyer_name IS 'اسم العميل (اختياري) — يختلف عن customer_name الذي يخزن اسم القماش في مبيعات الأقمشة';
COMMENT ON COLUMN income.buyer_phone IS 'رقم هاتف العميل (اختياري)';

