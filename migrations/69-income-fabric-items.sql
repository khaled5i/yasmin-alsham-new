-- Migration 69: بنود القماش المتعدّدة في مبيعة الأقمشة الواحدة (fabric_items)
-- ----------------------------------------------------------------------------
-- الهدف:
--   السماح بإضافة عدّة أقمشة (كل قماش مع كميته بالمتر) داخل مبيعة/فاتورة واحدة.
--   يبقى `amount` هو الإجمالي الكلّي للمبيعة (مبلغ واحد)، بينما تُخزَّن تفاصيل كل
--   قماش وكميّته في عمود JSONB جديد `fabric_items`.
--
--   شكل القيمة (مصفوفة كائنات):
--     [
--       { "inventory_id": "uuid|null", "name": "اسم القماش", "quantity_meters": 3.5 },
--       { "inventory_id": "uuid|null", "name": "اسم قماش آخر", "quantity_meters": 2 }
--     ]
--
--   • customer_name يبقى يحمل اسم القماش الأول (توافقاً مع العرض والإحصائيات القديمة).
--   • quantity_meters (العمود المفرد الموجود) يحمل مجموع الأمتار الكلّي للمبيعة.
--   • السجلات القديمة تبقى fabric_items = NULL وتُعامَل كقماش واحد (توافق رجعي).
--
--   عند الإرسال للمحاسبة (الأستاذ) يُبنى بند فاتورة مستقل لكل قماش مع كميّته الفعلية
--   بالمتر، ويُوزَّع الإجمالي الكلّي على البنود بنسبة الأمتار.
--
--   ⚠️ هذه الهجرة مطلوبة مع النشر (deploy).
-- ============================================================================

ALTER TABLE income
  ADD COLUMN IF NOT EXISTS fabric_items JSONB;

COMMENT ON COLUMN income.fabric_items IS
  'بنود القماش المتعدّدة للمبيعة: مصفوفة [{inventory_id, name, quantity_meters}]. amount يبقى الإجمالي الكلّي. NULL = مبيعة قماش واحد (توافق رجعي).';

