-- عند 403 في أحد المسارات، افحص بالترتيب — ولا تتراجع عن الترحيل في أي منها:
--   1. هل الحساب موقوف (is_active = false)؟ هذا رفض **مشروع** بعد تشديد
--      البوابة. العلاج تفعيل الحساب، لا التراجع.
--   2. هل دور الحساب ليس admin؟ رفض مشروع.
--   3. هل إصلاح الكود منشور؟ إن لم يكن، فهذا سبب الرفض. انشره.
