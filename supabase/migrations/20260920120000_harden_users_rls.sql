-- وإن منع القسم 3 مساراً مشروعاً: ❌ لا تُسقط المشغّل — ذلك يفتح نافذة
-- إعادة تنشيط مكشوفة. ✅ صحّح جسم الدالة بـCREATE OR REPLACE داخل معاملة
-- واحدة؛ المشغّل يبقى مركّباً فلا توجد لحظة بلا حماية.
