BEGIN;

-- ────────────────────────────────────────────────────────────────────────────
-- القسم 1 — إغلاق مسار تصعيد الصلاحية (SEC-02)
--
-- "Authenticated users can insert users"  INSERT  WITH CHECK (true)
-- "Authenticated users can delete users"  DELETE  USING      (true)
--
-- أي مستخدم مسجّل يحذف صفّه ثم يدرج صفاً جديداً بنفس auth.uid() وبدور admin.
-- الحارس prevent_users_role_change يعمل BEFORE UPDATE فقط فلا يعترض أياً منهما.
--
-- لا يوجد في التطبيق INSERT أو DELETE على users من جهة العميل. الإنشاء
-- والحذف عبر /api/workers/* بمفتاح الخدمة الذي يتجاوز RLS ولا يتأثر.
-- ────────────────────────────────────────────────────────────────────────────

DROP POLICY IF EXISTS "Authenticated users can insert users" ON public.users;
DROP POLICY IF EXISTS "Authenticated users can delete users" ON public.users;

-- ────────────────────────────────────────────────────────────────────────────
-- القسم 2 — منع الزائر غير المسجّل من قراءة جدول المستخدمين (SEC-03)
--
-- ⚠️ اقرأ الشرط السابق في رأس الملف قبل تشغيل هذا القسم.
--
-- "Anyone can view active users" TO public تكشف 25 صفاً تحوي email و phone
-- و full_name و role لأي زائر يحمل مفتاح anon المشحون في حزمة المتصفح.
--
-- الشرط يبقى كما هو ويُقصر على authenticated:
--   • كل مستخدم مسجّل يقرأ ما كان يقرأه بالضبط — بلا تغيير.
--   • الزائر غير المسجّل لا يقرأ شيئاً.
--
-- ⚠️ احتواء جزئي لا إغلاق كامل: الدور authenticated يشمل أيضاً أي عميل مسجّل
--    وأي حساب موقوف ما زال يحمل رمزاً صالحاً. القراءة بين الأدوار تبقى مفتوحة
--    كخطر مسجَّل، والتضييق النهائي مؤجَّل لما بعد جرد الصلاحيات (المرحلة 0).
-- ────────────────────────────────────────────────────────────────────────────

DROP POLICY IF EXISTS "Anyone can view active users" ON public.users;

CREATE POLICY "Authenticated users can view active users"
  ON public.users
  FOR SELECT
  TO authenticated
  USING (is_active = true);

COMMIT;


