-- إن تعطّلت قراءة مشروعة لدور معيّن، الإصلاح سياسة إضافية دقيقة لذلك الدور:
--
--   -- مثال فقط — لا تشغّله بلا حاجة مثبتة:
--   -- CREATE POLICY "<دور> can view <ما يحتاجه>"
--   --   ON public.users FOR SELECT TO authenticated
--   --   USING (<شرط دقيق للدور>);
