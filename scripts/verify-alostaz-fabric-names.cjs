// Recording-only HTTP adapter: no production tokens, invoices or product writes.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
const cache = new Map()

function load(file) {
  file = path.resolve(file)
  if (cache.has(file)) return cache.get(file).exports
  const module = { exports: {} }
  cache.set(file, module)
  const source = fs.readFileSync(file, 'utf8')
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  })
  const localRequire = spec => spec.startsWith('.')
    ? load(path.resolve(path.dirname(file), spec + '.ts'))
    : spec.startsWith('@/') ? load(path.join(root, 'src', spec.slice(2) + '.ts')) : require(spec)
  new Function('require', 'module', 'exports', outputText)(localRequire, module, module.exports)
  return module.exports
}

const previousFetch = global.fetch
const envKeys = ['ALOSTAZ_API_TOKEN', 'ALOSTAZ_BASE_URL', 'ALOSTAZ_FABRICS_INVOICE_STATUS']
const previousEnv = Object.fromEntries(envKeys.map(key => [key, process.env[key]]))
process.env.ALOSTAZ_API_TOKEN = 'local-recording-test'
process.env.ALOSTAZ_BASE_URL = 'https://alostaz.invalid/api'
process.env.ALOSTAZ_FABRICS_INVOICE_STATUS = 'issued'

const calls = []
let products
let rejectUpdate = false
let ignoreUpdate = false
global.fetch = async (url, init = {}) => {
  assert.ok(url.startsWith('https://alostaz.invalid/api/'))
  const endpoint = url.slice('https://alostaz.invalid/api'.length)
  const method = init.method || 'GET'
  const body = init.body ? JSON.parse(init.body) : undefined
  calls.push({ endpoint, method, body, headers: init.headers })
  let result
  const productMatch = endpoint.match(/^\/products\/(\d+)$/)
  if (productMatch) {
    const product = products.get(Number(productMatch[1]))
    assert.ok(product)
    if (method === 'PUT') {
      assert.deepEqual(Object.keys(body), ['name'])
      if (rejectUpdate) return new Response(JSON.stringify({ message: 'Product update denied' }), { status: 403 })
      if (!ignoreUpdate) product.name = body.name
    } else assert.equal(method, 'GET')
    result = { data: { ...product } }
  } else if (endpoint === '/products') {
    assert.equal(method, 'POST')
    result = { id: 100 }
  } else if (endpoint === '/partners') {
    assert.equal(method, 'GET')
    result = { data: [{ id: 1, name: 'عميل جديد' }] }
  } else if (endpoint === '/invoices') {
    assert.equal(method, 'POST')
    // BT-153 is generated by Alostaz from the product name, not description.
    for (const line of body.line_items) assert.ok([...products.get(line.product_id).name].length >= 3)
    result = { id: 900, code: 'LOCAL-TEST' }
  } else throw new Error(`Unexpected endpoint: ${endpoint}`)
  return new Response(JSON.stringify(result), { status: 200 })
}

async function run() {
  const { normalizeAlostazFabricName } = load(path.join(root, 'src/lib/alostaz-fabric-names.ts'))
  const service = load(path.join(root, 'src/lib/services/alostaz-service.ts'))
  for (const name of ['SA', 'SS', 'SH', 'A', '12']) assert.equal(normalizeAlostazFabricName(name), `قماش ${name}`)
  assert.equal(normalizeAlostazFabricName('  SA  '), 'قماش SA')
  assert.equal(normalizeAlostazFabricName(''), 'قماش')
  assert.equal(normalizeAlostazFabricName('قماش SA'), 'قماش SA')
  assert.equal(normalizeAlostazFabricName('ساتان'), 'ساتان')
  assert.equal(normalizeAlostazFabricName('SAA'), 'SAA')
  assert.equal(normalizeAlostazFabricName('A'.repeat(1000)).length, 1000)
  assert.throws(() => normalizeAlostazFabricName('A'.repeat(1001)), /1000/)
  const input = {
    invoice_number: 123, payment_method: 'network', date: '2026-10-05T10:00:00Z',
    lines: [
      { product_id: 67, description: 'SA', amount: 60, quantity_meters: 3 },
      { product_id: 25, description: 'SS', amount: 23, quantity_meters: 1 },
      { product_id: 12, description: 'SH', amount: 46, quantity_meters: 2 },
      { product_id: 4, description: 'قماش سادة', amount: 10, quantity_meters: 1 },
      { product_id: 99, description: 'رسوم شحن — FS-123', amount: 50, quantity_meters: 1 },
      { product_id: 67, description: 'SA', amount: 20, quantity_meters: 1 },
    ],
  }
  const original = structuredClone(input)
  const inventoryFields = { units: [{ id: 67, content: 1, purchase_price: 500, sale_price: 2000 }], supports_inventory: true }
  products = new Map([[67, { id: 67, name: 'SA', ...structuredClone(inventoryFields) }],
    [25, { id: 25, name: 'SS' }], [12, { id: 12, name: 'SH' }],
    [4, { id: 4, name: 'قماش سادة' }], [99, { id: 99, name: 'رسوم شحن' }]])
  await service.createInvoiceForFabricSale(input)
  assert.deepEqual(input, original)
  assert.deepEqual(products.get(67), { id: 67, name: 'قماش SA', ...inventoryFields })
  assert.equal(calls.filter(c => c.method === 'PUT').length, 3)
  const invoice = calls.find(c => c.endpoint === '/invoices').body
  assert.deepEqual(invoice.line_items.map(l => l.product_id), input.lines.map(l => l.product_id))
  assert.deepEqual(invoice.line_items.map(l => l.description), ['قماش SA', 'قماش SS', 'قماش SH', 'قماش سادة', 'رسوم شحن — FS-123', 'قماش SA'])
  assert.equal(invoice.line_items[0].unit_quantity, 3000)
  assert.equal(invoice.line_items[0].unit_price, 2000)
  assert.equal(invoice.payments[0].amount, 20900)
  assert.ok(calls.every(c => c.headers['X-Branch-Id'] === '3'))
  calls.length = 0
  await service.createInvoiceForFabricSale(input)
  assert.equal(calls.filter(c => c.method === 'PUT').length, 0, 'already corrected products are not updated again')

  for (const failure of ['reject', 'unconfirmed']) {
    calls.length = 0
    products.get(67).name = 'SA'
    rejectUpdate = failure === 'reject'
    ignoreUpdate = failure === 'unconfirmed'
    await assert.rejects(service.createInvoiceForFabricSale(input))
    assert.ok(calls.every(c => !['/invoices', '/partners'].includes(c.endpoint)))
  }
  rejectUpdate = ignoreUpdate = false
  calls.length = 0
  await assert.rejects(service.createInvoiceForFabricSale({ ...input, lines: [{ ...input.lines[0], description: 'A'.repeat(1001) }] }), /1000/)
  assert.equal(calls.length, 0)
  await service.createProduct('SA', { branchId: 3, supportsInventory: true, purchasePrice: 5, salePrice: 20 })
  assert.equal(calls[0].body.name, 'قماش SA')
  assert.equal(calls[0].body.units[0].purchase_price, 500)
  assert.equal(calls[0].body.units[0].sale_price, 2000)

  // Existing invoices exit before product reads/updates, sending claims or invoice POSTs.
  calls.length = 0
  const { sendFabricIncomeToAlostaz } = load(path.join(root, 'src/lib/server/alostaz-fabric-invoice.ts'))
  const query = {
    select() { return this }, eq() { return this },
    single: async () => ({ data: { id: 'old-sale', branch: 'fabrics', category: 'fabric_sale', alostaz_invoice_id: 764, alostaz_invoice_code: 'INV-26-3-000165' } }),
  }
  const admin = { from(table) { assert.equal(table, 'income'); return query } }
  assert.equal((await sendFabricIncomeToAlostaz(admin, 'old-sale')).kind, 'already_sent')
  assert.equal(calls.length, 0)
  console.log('PASS: product names and descriptions, stable IDs/pricing/shipping, failures stop sending, and existing invoices are skipped. No live writes.')
}

run().catch(error => { console.error(error); process.exitCode = 1 }).finally(() => {
  global.fetch = previousFetch
  for (const key of envKeys) if (previousEnv[key] === undefined) delete process.env[key]; else process.env[key] = previousEnv[key]
})
